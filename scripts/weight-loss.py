"""Write src/data/weightLoss.ts: the pounds lost by 1000 people on an invented
weight-loss drug, the fourth bag of the sampling demo.

Normal with mean 12 and standard deviation 6, rounded to one decimal, from a
fixed seed so the bag never changes. A negative loss is a gain. Python's
generator, not JavaScript's, so a printed copy made from the same seed lists
the same 1000 numbers in the same order.

    python3 scripts/weight-loss.py
"""
import random
from pathlib import Path

N = 1000
SEED = 20261026
OUT = Path(__file__).resolve().parent.parent / "src" / "data" / "weightLoss.ts"

rng = random.Random(SEED)
data = [round(rng.gauss(12, 6), 1) for _ in range(N)]

rows = [", ".join(f"{v:.1f}" for v in data[i:i + 20]) for i in range(0, N, 20)]
OUT.write_text(
    "// Generated by scripts/weight-loss.py, seed %d. Edit that, not this.\n"
    "// Pounds lost by %d people on a new drug, in person order 1 to %d.\n\n"
    "export const WEIGHT_LOSS: number[] = [\n  %s,\n];\n"
    % (SEED, N, N, ",\n  ".join(rows))
)
mu = sum(data) / N
sigma = (sum((v - mu) ** 2 for v in data) / N) ** 0.5
print(f"{N} values, mu {mu:.2f}, sigma {sigma:.2f}, min {min(data)}, max {max(data)}")
